"""Worktree lifecycle — every agent checkout is created, tracked and retired by awgit.

The defect this closes: agents made worktrees ad hoc (``git worktree add`` from a
shell, a harness, a workflow) and nothing ever retired them. A checkout nobody
remembers is a checkout nobody removes; a drive fills, and the only way back is a
human walking hundreds of directories by hand deciding which ones hold work.

Lifecycle, all in this module:

* ``new``      — create under a configured ROOT and write a registry row (owner
                 session, purpose, base, created, last activity).
* ``adopt``    — write rows for worktrees git knows about that have none yet
                 (harness- or shell-made trees), so nothing stays untracked.
* ``snapshot`` — record EVERY uncommitted byte of a tree (tracked edits, staged
                 work, untracked files, non-build ignored files) as a commit on
                 ``refs/heads/reclaim/<name>`` through a PRIVATE index, then
                 read it back: the tree's own index is never touched.
* ``done``     — snapshot when needed, cut junctions/symlinks (a forced remove
                 recurses THROUGH a junction and empties its target), remove,
                 record the reap in the ledger.
* ``restore``  — recreate a retired tree from its ledger row: the branch at its
                 old head, with the snapshot re-applied as uncommitted changes.

Git stays ground truth for what EXISTS; the registry adds only what git cannot
know (who made a tree and why). One file per row, written atomically — many
sessions create trees at once, and one shared JSON would lose updates silently.
The reap ledger is append-only JSONL so a later session can find any retired
tree by name.

Settings (roots, idle thresholds, drive floors) come from a JSON file —
``$AWGIT_WT_SETTINGS`` or ``~/.aither/awgit/worktrees.json`` — so a settings
sync tool can carry them between machines; absent, the defaults are the repo's
own ``.worktrees`` and conservative thresholds.
"""

from __future__ import annotations

import glob as _glob
import hashlib
import json
import os
import shutil
import subprocess
import tempfile
import time
from pathlib import Path
from typing import Dict, List, Optional, Sequence, Tuple

from awgit import worktree as wt

SETTINGS_ENV = "AWGIT_WT_SETTINGS"
RECLAIM_PREFIX = "refs/heads/reclaim/"

DEFAULT_SETTINGS: Dict[str, object] = {
    # Directories (globs allowed) whose children are agent worktrees. A relative
    # entry is resolved against the main worktree root.
    "roots": [".worktrees"],
    "idle_hours": 48.0,           # a tree idle this long is retired
    "pressure_idle_hours": 6.0,   # ... this long when its drive is under the floor
    "pressure_free_gb": 50.0,     # per-drive free-space floor
    "unregistered_grace_hours": 24.0,
    "snapshot_max_mb": 200.0,     # refuse (keep) a snapshot that would add more
    "repo_free_floor_gb": 5.0,    # never grow the object store below this
    # argv templates run after each reap, ``{name} {ref} {path} {gb_freed} ...``
    # filled from the ledger entry — how a memory or knowledge store hears of it.
    "record_commands": [],
}

#: Plugin hook (multi) a host registers to hear of every retired tree.
REAPED_HOOK = "worktree_reaped"

#: Untracked/ignored paths under these names are caches one command rebuilds;
#: they are never snapshotted and never make a tree "hold work".
REGENERABLE_DIRS = frozenset({
    "node_modules", "__pycache__", ".venv", "venv", ".pytest_cache", ".ruff_cache",
    ".mypy_cache", ".tox", ".next", ".turbo", ".cache"})

#: Ignored files of these shapes are NEVER written into a snapshot ref (a ref is
#: one push away from a remote). A tree holding one is kept, not retired.
SECRET_SHAPES = (".env", ".pem", ".key", ".pfx", ".p12", ".keystore", ".jks",
                 "id_rsa", "id_ed25519", ".npmrc", ".pypirc", "credentials",
                 "secret", "token", "bearer", ".netrc", ".htpasswd")


#: Ignored paths that are NOT work: regenerable caches and copies of a file the
#: main tree keeps canonically. Dropped with the tree, never snapshotted. Printed
#: on every managed run so the list stays visible.
DISPOSABLE_IGNORED = (
    (".tech-debt-ids/", "id-allocation cache, regenerated on demand"),
    (".egg-info/", "pip build metadata, regenerated by install"),
)


def split_ignored(main: Optional[Path], paths: Sequence[str]) -> Tuple[List[str], List[str]]:
    """(work, disposable). A secret-shaped ignored file is disposable ONLY when the
    main tree holds the same path (it is a harness copy of the canonical file);
    otherwise it stays in ``work`` and the secret check keeps the tree."""
    work: List[str] = []
    gone: List[str] = []
    for rel in paths:
        r = rel.replace("\\", "/")
        if any(r.endswith(sfx) or ("/" + sfx) in ("/" + r) for sfx, _ in DISPOSABLE_IGNORED):
            gone.append(rel)
        elif secret_shaped(r) and main is not None and (main / r.rstrip("/")).is_file():
            gone.append(rel)
        else:
            work.append(rel)
    return work, gone


def secret_inside(tree: Path, rels: Sequence[str], cap: int = 20000) -> List[str]:
    """Secret-shaped names at or under ``rels`` (an ignored DIRECTORY is walked)."""
    hits: List[str] = []
    seen = 0
    for rel in rels:
        if secret_shaped(rel):
            hits.append(rel)
            continue
        p = tree / rel
        if p.is_dir() and not p.is_symlink():
            for dp, dns, fns in os.walk(p):
                dns[:] = [d for d in dns if d not in REGENERABLE_DIRS]
                for f in fns:
                    seen += 1
                    if seen > cap:
                        return hits + [f"{rel} (too many files to inspect)"]
                    if secret_shaped(f):
                        hits.append(os.path.relpath(os.path.join(dp, f), tree).replace("\\", "/"))
    return hits


# ── plumbing ────────────────────────────────────────────────────────────────

def _git(cwd: Optional[Path], *args: str, env: Optional[Dict[str, str]] = None,
         timeout: int = 1800) -> subprocess.CompletedProcess:
    try:
        return subprocess.run(
            ["git", *args], cwd=str(cwd) if cwd else None, capture_output=True,
            text=True, encoding="utf-8", errors="replace", env=env, timeout=timeout,
            creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0),
        )
    except (OSError, subprocess.TimeoutExpired) as exc:
        return subprocess.CompletedProcess(["git", *args], 124, "", str(exc))


def _out(cwd: Optional[Path], *args: str) -> str:
    p = _git(cwd, *args)
    return p.stdout.strip() if p.returncode == 0 else ""


def _norm(path: object) -> str:
    return os.path.normcase(os.path.abspath(str(path))).replace("\\", "/").rstrip("/")


def state_dir() -> Path:
    from awgit.data_root import vcs_data_root

    d = vcs_data_root() / "worktrees"
    (d / "rows").mkdir(parents=True, exist_ok=True)
    return d


def ledger_path() -> Path:
    return state_dir() / "reaped.jsonl"


# ── settings ────────────────────────────────────────────────────────────────

def settings_path() -> Path:
    explicit = os.environ.get(SETTINGS_ENV, "").strip()
    return Path(explicit) if explicit else Path.home() / ".aither" / "awgit" / "worktrees.json"


def load_settings() -> Dict[str, object]:
    out = dict(DEFAULT_SETTINGS)
    p = settings_path()
    if p.is_file():
        try:
            data = json.loads(p.read_text(encoding="utf-8"))
        except (OSError, ValueError) as exc:
            raise RuntimeError(f"unreadable worktree settings {p}: {exc}") from exc
        if isinstance(data, dict):
            out.update({k: v for k, v in data.items() if k in DEFAULT_SETTINGS})
    return out


def resolve_roots(settings: Dict[str, object], main: Optional[Path]) -> List[Path]:
    """Expand configured roots (globs allowed) to existing directories."""
    roots: List[Path] = []
    for raw in settings.get("roots") or []:
        s = str(raw)
        if not os.path.isabs(s) and main is not None:
            s = str(main / s)
        hits = _glob.glob(s) if any(c in s for c in "*?[") else [s]
        for h in hits:
            if os.path.isdir(h) and _norm(h) not in {_norm(r) for r in roots}:
                roots.append(Path(h))
    return roots


def under_roots(path: str, roots: Sequence[Path]) -> bool:
    p = _norm(path)
    return any(p.startswith(_norm(r) + "/") for r in roots)


def free_gb(path: object) -> float:
    try:
        return shutil.disk_usage(str(path)).free / 1e9
    except OSError:
        return float("inf")


def idle_threshold(path: object, settings: Dict[str, object]) -> Tuple[float, str]:
    """(hours, why) — the per-DRIVE threshold: the floor is the tree's own drive."""
    free = free_gb(path)
    floor = float(settings["pressure_free_gb"])  # type: ignore[arg-type]
    if free < floor:
        return float(settings["pressure_idle_hours"]), f"drive {free:.0f} GB free < {floor:g} GB"  # type: ignore[arg-type]
    return float(settings["idle_hours"]), f"drive {free:.0f} GB free"  # type: ignore[arg-type]


# ── registry ────────────────────────────────────────────────────────────────

def row_id(path: object) -> str:
    return hashlib.sha256(_norm(path).encode("utf-8")).hexdigest()[:16]


def _row_file(path: object) -> Path:
    return state_dir() / "rows" / (row_id(path) + ".json")


def read_row(path: object) -> Optional[Dict[str, object]]:
    f = _row_file(path)
    try:
        return json.loads(f.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None


def write_row(row: Dict[str, object]) -> None:
    f = _row_file(row["path"])
    tmp = f.with_suffix(".tmp")
    tmp.write_text(json.dumps(row, indent=1, sort_keys=True), encoding="utf-8")
    os.replace(tmp, f)


def drop_row(path: object) -> None:
    try:
        _row_file(path).unlink()
    except OSError:
        return  # already gone; git is the ground truth for existence


def rows() -> List[Dict[str, object]]:
    out = []
    for f in sorted((state_dir() / "rows").glob("*.json")):
        try:
            out.append(json.loads(f.read_text(encoding="utf-8")))
        except (OSError, ValueError):
            continue  # a torn row is not a claim
    return out


def _owner() -> str:
    for k in ("AWGIT_ACTOR", "CLAUDE_SESSION_ID", "AITHER_SESSION_ID", "TERM_SESSION_ID"):
        if os.environ.get(k):
            return f"{k.lower()}:{os.environ[k]}"
    return f"pid:{os.getpid()}@{os.environ.get('COMPUTERNAME') or os.environ.get('HOSTNAME') or ''}"


def new_row(path: object, *, name: str, base: str = "", purpose: str = "",
            origin: str = "awgit", created: Optional[float] = None) -> Dict[str, object]:
    now = time.time()
    return {"id": row_id(path), "path": str(path), "name": name, "base": base,
            "purpose": purpose, "origin": origin,
            "owner": "(unknown: adopted)" if origin == "adopted" else _owner(),
            "created": created or now, "registered": now, "last_activity": now,
            "pinned": False}


# ── activity and liveness ───────────────────────────────────────────────────

def git_idle_hours(tree: Path) -> Optional[float]:
    """Hours since the newest of HEAD reflog, index/HEAD mtimes, the .git file."""
    stamps: List[float] = []
    out = _out(tree, "log", "-g", "-1", "--format=%ct", "HEAD")
    if out.isdigit():
        stamps.append(float(out))
    gd = _out(tree, "rev-parse", "--absolute-git-dir")
    for name in ("index", "HEAD", "ORIG_HEAD"):
        try:
            stamps.append(os.path.getmtime(os.path.join(gd, name)))
        except OSError:
            continue
    try:
        stamps.append(os.path.getmtime(tree / ".git"))
    except OSError:
        stamps.append(0.0)  # no .git stamp: a zero never wins max(); the others decide
    return (time.time() - max(stamps)) / 3600.0 if stamps else None


def live_claims(tree: Path) -> List[str]:
    """Reasons a tree is in use RIGHT NOW: a fresh session row, an active lease
    naming it, or a pinned registry row. Empty list = no live claim."""
    why: List[str] = []
    key = _norm(tree)
    try:
        from awgit import session as sess

        for r in sess.listing():
            if _norm(r.get("worktree", "")) == key and not r.get("stale"):
                why.append(f"live session {r.get('id')} ({int(r.get('idle_s', 0)) // 60} min idle)")
    except Exception as exc:  # noqa: BLE001 — an unreadable registry is a claim, not silence
        why.append(f"session registry unreadable: {exc}")
    try:
        from awgit.leases import LeaseRegistry

        for lz in LeaseRegistry().active_leases():
            tgt = str(lz.target)
            nt = _norm(tgt)
            if tgt == f"worktree:{tree.name}" or nt.startswith(key + "/") or nt == key:
                why.append(f"active lease {lz.lease_id} by {lz.actor}")
    except Exception as exc:  # noqa: BLE001
        why.append(f"lease registry unreadable: {exc}")
    row = read_row(tree)
    if row and row.get("pinned"):
        why.append("pinned in the worktree registry")
    return why


# ── snapshot ────────────────────────────────────────────────────────────────

def _err(p: subprocess.CompletedProcess) -> str:
    """The line that explains a failure: CRLF warnings and hints are noise."""
    lines = [ln for ln in (p.stderr or p.stdout or "").splitlines()
             if ln.strip() and not ln.startswith(("warning: in the working copy", "hint:"))]
    return " ".join(lines)[:240] or f"rc={p.returncode}"


def _excluded(rel: str) -> bool:
    parts = [p for p in rel.replace("\\", "/").split("/") if p]
    return any(p in REGENERABLE_DIRS for p in parts) or rel.endswith((".pyc", ".log"))


def secret_shaped(rel: str) -> bool:
    base = rel.replace("\\", "/").rstrip("/").rsplit("/", 1)[-1].lower()
    return any(s in base for s in SECRET_SHAPES)


def pending_paths(tree: Path, ignored_work: Sequence[str] = ()) -> Tuple[List[str], List[str]]:
    """(changed_tracked, new_files) a snapshot must carry, regenerable excluded."""
    changed = [p for p in _out(tree, "-c", "core.quotepath=off", "--no-optional-locks",
                                "diff", "--name-only", "HEAD").splitlines() if p]
    new = [p for p in _out(tree, "-c", "core.quotepath=off", "--no-optional-locks",
                           "ls-files", "--others", "--exclude-standard").splitlines()
           if p and not _excluded(p)]
    return changed, sorted(set(new) | {p for p in ignored_work if not _excluded(p)})


def _bytes(tree: Path, rels: Sequence[str]) -> int:
    total = 0
    for rel in rels:
        p = tree / rel
        if p.is_dir() and not p.is_symlink():
            for dp, dns, fns in os.walk(p):
                dns[:] = [d for d in dns if d not in REGENERABLE_DIRS]
                for f in fns:
                    try:
                        total += os.lstat(os.path.join(dp, f)).st_size
                    except OSError:
                        continue
        else:
            try:
                total += os.lstat(p).st_size
            except OSError:
                continue
    return total


def reclaim_ref_for(main: Path, name: str, commit: str) -> str:
    """``refs/heads/reclaim/<name>``; a different existing one gets a timestamp."""
    ref = RECLAIM_PREFIX + name
    have = _out(main, "rev-parse", "--verify", "-q", ref)
    if not have or have == commit:
        return ref
    return f"{ref}-{time.strftime('%Y%m%d%H%M%S')}"


def snapshot(tree: Path, name: str, *, ignored_work: Sequence[str] = (),
             max_mb: float = 200.0) -> Tuple[bool, str, Dict[str, object]]:
    """Commit every uncommitted byte of ``tree`` to a reclaim ref. (ok, msg, info).

    Private index seeded from the tree's OWN index (so staged-but-uncommitted
    work is carried — seeding from HEAD missed 42 files once), ``add -A`` plus
    forced adds for non-build ignored files, ``write-tree``, ``commit-tree -p
    HEAD``, ``update-ref`` (create-only). Then verified: with the private index
    holding the snapshot, the working tree must show no difference and no
    untracked non-cache file, and the ref must resolve to the commit.
    """
    info: Dict[str, object] = {"name": name, "path": str(tree)}
    main = wt.main_root(tree)
    head = _out(tree, "rev-parse", "HEAD")
    if main is None or not head:
        return False, "not a worktree with a HEAD", info
    info["head"] = head
    info["branch"] = _out(tree, "symbolic-ref", "-q", "--short", "HEAD")
    secret = [p for p in list(ignored_work) + pending_paths(tree)[1] if secret_shaped(p)]
    if secret:
        return False, f"secret-shaped file(s) would enter the ref, e.g. {secret[0]}", info
    changed, new = pending_paths(tree, ignored_work)
    size = _bytes(tree, changed + new)
    info["snapshot_bytes"] = size
    if size > max_mb * 1e6:
        return False, f"snapshot {size / 1e6:.0f} MB > cap {max_mb:g} MB", info
    gd = Path(_out(tree, "rev-parse", "--absolute-git-dir"))
    tmpd = tempfile.mkdtemp(prefix="awgit-snap-")
    idx = os.path.join(tmpd, "index")
    try:
        try:
            shutil.copyfile(gd / "index", idx)
        except OSError:
            r = _git(tree, "read-tree", "HEAD", env=dict(os.environ, GIT_INDEX_FILE=idx))
            if r.returncode != 0:
                return False, f"seed index: {r.stderr.strip()[:200]}", info
        env = dict(os.environ, GIT_INDEX_FILE=idx)
        env.setdefault("GIT_AUTHOR_NAME", "awgit-reclaim")
        env.setdefault("GIT_AUTHOR_EMAIL", "awgit-reclaim@localhost")
        env.setdefault("GIT_COMMITTER_NAME", env["GIT_AUTHOR_NAME"])
        env.setdefault("GIT_COMMITTER_EMAIL", env["GIT_AUTHOR_EMAIL"])
        excludes = [f":(exclude,glob)**/{d}/**" for d in sorted(REGENERABLE_DIRS)]
        # --sparse: in a sparse tree a file OUTSIDE the cone that is present on disk
        # (an agent wrote it anyway) is refused by a plain add (rc 1, "outside of your
        # sparse-checkout definition") — 7 of 80 retirements failed that way. Missing
        # skip-worktree entries are still never staged as deletions; the deletion
        # check below asserts it.
        r = _git(tree, "add", "-A", "--sparse", "--", ".", *excludes, env=env)
        if r.returncode != 0:
            return False, f"add -A: {_err(r)}", info
        forced = [p for p in ignored_work if not _excluded(p)]
        for i in range(0, len(forced), 100):
            r = _git(tree, "add", "-f", "--sparse", "--", *forced[i:i + 100], env=env)
            if r.returncode != 0:
                return False, f"add -f ignored work: {_err(r)}", info
        gone = {p for p in _git(tree, "-c", "core.quotepath=off", "diff", "--cached",
                                "--name-only", "--diff-filter=D", "HEAD", env=env
                                ).stdout.splitlines() if p}
        extra = sorted(gone - set(changed))
        if extra:
            return False, (f"snapshot would DELETE {len(extra)} file(s) the tree never "
                           f"deleted, e.g. {extra[0]}"), info
        r = _git(tree, "write-tree", env=env)
        tree_sha = r.stdout.strip() if r.returncode == 0 else ""
        if not tree_sha:
            return False, f"write-tree: {r.stderr.strip()[:200]}", info
        if tree_sha == _out(tree, "rev-parse", "HEAD^{tree}"):
            commit = head
        else:
            msg = (f"reclaim: {name} — uncommitted work at retirement\n\n"
                   f"path: {tree}\nbranch: {info['branch'] or '(detached)'}\n"
                   f"changed: {len(changed)} new: {len(new)}\n")
            r = _git(tree, "commit-tree", tree_sha, "-p", head, "-m", msg, env=env)
            commit = r.stdout.strip() if r.returncode == 0 else ""
            if not commit:
                return False, f"commit-tree: {r.stderr.strip()[:200]}", info
        # Verify BEFORE the ref is written: worktree vs snapshot index must agree.
        r = _git(tree, "-c", "core.quotepath=off", "diff", "--name-only", env=env)
        dif = [p for p in r.stdout.splitlines() if p and not _excluded(p)]
        r2 = _git(tree, "-c", "core.quotepath=off", "ls-files", "--others",
                  "--exclude-standard", env=env)
        left = [p for p in r2.stdout.splitlines() if p and not _excluded(p)]
        r3 = _git(tree, "diff", "--cached", "--quiet", commit, env=env)
        if r.returncode != 0 or r2.returncode != 0 or dif or left or r3.returncode != 0:
            return False, (f"snapshot verify FAILED: {len(dif)} differing, {len(left)} "
                           f"uncaptured, index==commit rc={r3.returncode}"), info
        ref = reclaim_ref_for(main, name, commit)
        r = _git(main, "update-ref", "-m", f"awgit reclaim {name}", ref, commit, "0" * 40)
        if r.returncode != 0 and _out(main, "rev-parse", "--verify", "-q", ref) != commit:
            return False, f"update-ref {ref}: {r.stderr.strip()[:200]}", info
        if _out(main, "rev-parse", "--verify", "-q", ref) != commit:
            return False, f"ref {ref} does not resolve to {commit}", info
        info.update(ref=ref, commit=commit, changed=len(changed), new=len(new))
        return True, f"snapshot {commit[:12]} -> {ref}", info
    finally:
        shutil.rmtree(tmpd, ignore_errors=True)


# ── retire / restore ────────────────────────────────────────────────────────

def pushed(tree: Path, head: str) -> bool:
    """HEAD is contained in some remote-tracking ref."""
    return bool(head) and bool(_out(tree, "branch", "-r", "--contains", head))


def remove_tree(main: Path, tree: Path) -> Tuple[bool, str]:
    """Cut every junction/symlink AS A LINK first, then remove. A forced remove
    recurses through a junction and empties its target; cut first, or keep."""
    from awgit.linkcut import unlink_links

    cut, stuck = unlink_links(str(tree))
    if stuck:
        return False, f"link not removable, kept: {stuck[0]}"
    r = _git(main, "worktree", "remove", "--force", str(tree))
    if r.returncode != 0 or tree.exists():
        return False, f"remove failed rc={r.returncode}: {(r.stderr or r.stdout).strip()[:200]}"
    return True, f"removed{f' ({len(cut)} link(s) cut first)' if cut else ''}"


def record_reap(entry: Dict[str, object]) -> None:
    """Append to the ledger; then tell memory/knowledge sinks (best effort, loud)."""
    entry = dict(entry, ts=time.time(), when=time.strftime("%Y-%m-%dT%H:%M:%S"))
    with open(ledger_path(), "a", encoding="utf-8") as fh:
        fh.write(json.dumps(entry, sort_keys=True) + "\n")
    from awgit import plugins

    plugins.call_all(REAPED_HOOK, entry)  # a host's sinks; a failing one is logged, skipped
    for argv in (load_settings().get("record_commands") or []):
        run_sink(argv, entry)


def run_sink(argv: Sequence[str], entry: Dict[str, object]) -> bool:
    """Run one configured recorder (argv template, ``{key}`` filled from the entry).
    A sink that fails is reported, never fatal: the ledger line is already written."""
    fields = {k: str(v) for k, v in entry.items()}
    fields.setdefault("gb_freed", f"{int(entry.get('bytes_freed', 0) or 0) / 1e9:.2f}")
    try:
        cmd = [str(a).format(**fields) for a in argv]
    except (KeyError, IndexError, ValueError) as exc:
        print(f"awgit: note: record command {argv!r} has a bad placeholder: {exc}")
        return False
    try:
        p = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8",
                           errors="replace", timeout=60,
                           creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0))
    except (OSError, subprocess.TimeoutExpired) as exc:
        print(f"awgit: note: record command {cmd[0]} failed: {exc}")
        return False
    if p.returncode != 0:
        print(f"awgit: note: record command {cmd[0]} rc={p.returncode}: "
              f"{(p.stderr or p.stdout).strip()[:160]}")
    return p.returncode == 0


def ledger(name: str = "") -> List[Dict[str, object]]:
    out: List[Dict[str, object]] = []
    try:
        lines = ledger_path().read_text(encoding="utf-8").splitlines()
    except OSError:
        return out
    for ln in lines:
        try:
            e = json.loads(ln)
        except ValueError:
            continue
        tail = _norm(e.get("path", "")).endswith("/" + name.lower())
        if not name or e.get("name") == name or tail:
            out.append(e)
    return out


def done(tree: Path, *, ignored_work: Sequence[str] = (), max_mb: float = 200.0,
         reason: str = "done", require_idle_hours: float = 0.0) -> Tuple[bool, str]:
    """Retire one tree: snapshot if it holds anything unpushed, then remove."""
    tree = Path(tree)
    main = wt.main_root(tree)
    if main is None or _norm(main) == _norm(tree):
        return False, "refusing: not a linked worktree (or it is the main one)"
    try:
        cwd = _norm(os.getcwd())
    except OSError:
        cwd = ""
    if cwd == _norm(tree) or cwd.startswith(_norm(tree) + "/"):
        return False, "refusing: your shell is inside it — cd out first"
    if require_idle_hours:
        idle = git_idle_hours(tree)
        if idle is None or idle < require_idle_hours:
            return False, f"refusing: active {idle if idle is not None else '?'}h ago"
    head = _out(tree, "rev-parse", "HEAD")
    branch = _out(tree, "symbolic-ref", "-q", "--short", "HEAD")
    changed, new = pending_paths(tree, ignored_work)
    entry: Dict[str, object] = {"name": tree.name, "path": str(tree), "head": head,
                                "branch": branch, "reason": reason,
                                "pushed": pushed(tree, head)}
    if changed or new or not branch:
        ok, msg, info = snapshot(tree, tree.name, ignored_work=ignored_work, max_mb=max_mb)
        if not ok:
            return False, f"kept — snapshot refused: {msg}"
        entry.update(ref=info["ref"], commit=info["commit"],
                     snapshot_bytes=info.get("snapshot_bytes", 0))
    else:
        entry["ref"] = f"refs/heads/{branch}"
    row = read_row(tree) or {}
    entry.update(purpose=row.get("purpose", ""), owner=row.get("owner", ""),
                 base=row.get("base", ""))
    entry["bytes_freed"] = dir_bytes(tree)
    ok, msg = remove_tree(main, tree)
    if not ok:
        return False, f"kept — {msg}"
    drop_row(tree)
    record_reap(entry)
    return True, (f"retired {tree} ({msg}; restore: awgit wt restore {tree.name}; "
                  f"ref {entry['ref']})")


def dir_bytes(path: Path) -> int:
    total = 0
    for dp, dns, fns in os.walk(path):
        for f in fns:
            try:
                total += os.lstat(os.path.join(dp, f)).st_size
            except OSError:
                continue
    return total


def restore(name: str, *, dest: Optional[Path] = None,
            cwd: Optional[Path] = None) -> Tuple[bool, str]:
    """Recreate a retired tree: branch at its head, snapshot re-applied uncommitted."""
    hits = ledger(name)
    if not hits:
        return False, f"no reaped worktree named {name!r} in {ledger_path()}"
    e = hits[-1]
    main = wt.main_root(cwd)
    if main is None:
        return False, "not inside a git repository"
    target = Path(dest) if dest else Path(str(e["path"]))
    if target.exists():
        return False, f"{target} already exists"
    head = str(e.get("head") or "")
    branch = str(e.get("branch") or "")
    commit = str(e.get("commit") or "")
    on_branch = branch and _out(main, "rev-parse", "--verify", "-q", f"refs/heads/{branch}") == head
    busy = {b for _, _, b in wt.listing(main)}
    if on_branch and branch not in busy:
        r = _git(main, "worktree", "add", str(target), branch)
    else:
        nb = f"restore/{name}-{time.strftime('%Y%m%d%H%M%S')}"
        r = _git(main, "worktree", "add", "-b", nb, str(target), head or commit)
    if r.returncode != 0:
        return False, f"worktree add: {(r.stderr or r.stdout).strip()[:300]}"
    if commit and commit != head:
        diff = subprocess.run(["git", "diff", "--binary", head, commit], cwd=str(main),
                              capture_output=True,
                              creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0))
        ap = subprocess.run(["git", "apply", "--binary", "-"], cwd=str(target),
                            input=diff.stdout, capture_output=True,
                            creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0))
        if diff.returncode != 0 or ap.returncode != 0:
            return False, (f"restored {target} at {head[:12]} but re-applying the snapshot "
                           f"failed: {ap.stderr.decode('utf-8', 'replace')[:300]} — the work is "
                           f"intact on {e.get('ref')}")
    write_row(new_row(target, name=name, base=head, purpose=str(e.get("purpose", "")),
                      origin="restored"))
    return True, f"restored {target} from {e.get('ref')}"


# ── adoption and listing ────────────────────────────────────────────────────

def adopt(roots: Optional[Sequence[Path]] = None, cwd: Optional[Path] = None,
          everything: bool = False) -> List[str]:
    """Register every git-known linked worktree (under ``roots``, or all with
    ``everything``) that has no row. Returns the adopted paths."""
    adopted: List[str] = []
    listing = wt.listing(cwd)
    for i, (path, _sha, _branch) in enumerate(listing):
        if i == 0:
            continue  # the main worktree is never an agent tree
        if not everything and roots is not None and not under_roots(path, roots):
            continue
        if read_row(path) is not None or not os.path.isdir(path):
            continue
        try:
            created = os.path.getctime(path)
        except OSError:
            created = None
        write_row(new_row(path, name=Path(path).name, origin="adopted", created=created))
        adopted.append(path)
    return adopted


def describe(path: str, *, size: bool = False) -> Dict[str, object]:
    tree = Path(path)
    row = read_row(path) or {}
    head = _out(tree, "rev-parse", "HEAD") if tree.is_dir() else ""
    st = _out(tree, "--no-optional-locks", "status", "--porcelain") if tree.is_dir() else ""
    idle = git_idle_hours(tree) if tree.is_dir() else None
    d: Dict[str, object] = {
        "path": path, "name": tree.name, "exists": tree.is_dir(),
        "registered": bool(row), "origin": row.get("origin", ""),
        "owner": row.get("owner", ""), "purpose": row.get("purpose", ""),
        "idle_h": round(idle, 1) if idle is not None else None,
        "dirty": len([ln for ln in st.splitlines() if ln.strip()]),
        "pushed": pushed(tree, head) if head else False,
        "live": live_claims(tree) if tree.is_dir() else [],
    }
    if size and tree.is_dir():
        d["gb"] = round(dir_bytes(tree) / 1e9, 2)
    return d
